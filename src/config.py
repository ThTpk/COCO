# ---------------------------------------------------------------------------
# นิยามของมุมกล้อง
#
# ใช้ระบบพิกัดแบบ glTF / three.js:  +X = ขวาของตัวละคร, +Y = ขึ้น, +Z = เข้าหาผู้ชม
#
# แต่ละมุมบอกว่า "พิกเซล (u, v) ของภาพ แมปไปแกนโลกไหน"
#   axis_u : แกนโลกที่วิ่งตามความกว้างของภาพ (u เพิ่ม -> ค่าแกนนั้นเพิ่ม)
#   axis_v : แกนโลกที่วิ่งตามความสูงของภาพ (v เพิ่มคือลงล่าง -> ค่าแกนนั้นลด)
#   flip_u : ภาพนี้ต้องพลิกซ้ายขวาก่อนใช้หรือไม่
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class ViewSpec:
    name: str
    axis_u: str          # "x" | "z"
    flip_u: bool         # พลิกแนวนอนก่อนใช้
    depth_axis: str      # แกนที่มุมนี้ "มองไม่เห็น" (ใช้ตอน carve)
    required: bool = True


VIEWS: dict[str, ViewSpec] = {
    # มองจากด้านหน้า: กล้องอยู่ +Z มองไปทาง -Z
    #   u เพิ่ม (ซ้าย->ขวาของภาพ) = +X,  มองไม่เห็นแกน Z
    "front": ViewSpec("front", axis_u="x", flip_u=False, depth_axis="z"),
    # มองจากด้านหลัง: กล้องอยู่ -Z มองไปทาง +Z
    #   u เพิ่มในภาพ = -X ของโลก  ->  ต้องพลิกซ้ายขวาให้ตรงกับ front
    "back": ViewSpec("back", axis_u="x", flip_u=True, depth_axis="z"),
    # มุมข้างสองใบ กล้องอยู่คนละฝั่งของตัวละคร
    #
    # flip_u ตรงนี้เป็นแค่ *ค่าเริ่มต้นเวลาเดาทิศหันหน้าไม่ได้* เท่านั้น
    # ปกติ `normalize_view` จะดูจากภาพเองว่าตัวละครหันหน้าไปทางไหน แล้วพลิก
    # ให้หน้าชี้ไป +Z (ขวาของภาพ) เสมอ ซึ่งเชื่อถือได้กว่าการเดาจากชื่อไฟล์
    # มาก เพราะคนตั้งชื่อ "left/right" กันคนละความหมาย (ข้างซ้ายของตัวละคร
    # กับ กล้องอยู่ทางซ้าย) อยู่เป็นประจำ
    "side": ViewSpec("side", axis_u="z", flip_u=False, depth_axis="x"),
    # มุมเสริม ถ้ามีภาพข้างอีกฝั่ง
    "side_r": ViewSpec("side_r", axis_u="z", flip_u=True, depth_axis="x", required=False),
}

# ชื่อไฟล์ที่ยอมรับต่อมุม (ไม่สนตัวพิมพ์ใหญ่เล็ก)
VIEW_ALIASES: dict[str, tuple[str, ...]] = {
    "front": ("front", "f", "หน้า", "0", "000"),
    "back":  ("back", "b", "rear", "หลัง", "180"),
    "side":  ("side", "s", "left", "side_l", "ข้าง", "270"),
    "side_r": ("side_r", "right", "90"),
}

IMAGE_EXTS = (".png", ".jpg", ".jpeg", ".webp", ".bmp")


@dataclass
class PipelineConfig:
    # --- preprocess ---
    canvas: int = 1024              # ความสูงของ canvas หลัง normalize (พิกเซล)
    margin: float = 0.04            # เว้นขอบบน/ล่างเป็นสัดส่วนของ canvas
    mask_threshold: int = 127       # ตัด alpha/ความสว่างที่ค่านี้
    bg_tolerance: int = 18          # ความคลาดสีพื้นหลัง (ใช้เมื่อไม่มี alpha)
    # โมเดล rembg: isnet-general-use ใช้ได้กับทุกวัตถุ รวมถึงตัวละครที่ไม่ใช่มนุษย์
    # (u2net_human_seg เทรนมากับคนจริง จะพลาดกับสัตว์ประหลาด/หุ่นยนต์/ตัวการ์ตูน)
    rembg_model: str = "isnet-general-use"
    grabcut_size: int = 768         # ย่อภาพเหลือด้านยาวเท่านี้ก่อนรัน GrabCut
                                    # ต่ำกว่านี้ช่องแคบอย่างหว่างขาจะหายไป
    grabcut_iters: int = 7          # จำนวนรอบของ GrabCut
    # ลำดับวิธีแยกพื้นหลัง ลองจากซ้ายไปขวา ใช้ตัวแรกที่สำเร็จ
    #
    # rembg มาก่อน GrabCut เพราะภาพ character sheet ที่ใช้จริงมีพื้นหลังเป็น
    # ฉากวาด (ซุ้มโค้ง พื้นกระเบื้อง คบไฟ) ไม่ใช่สีพื้น GrabCut กับวิธีสีพื้น
    # จะกิน *พื้นกระเบื้องใต้เท้า* เข้ามาด้วย ซึ่งพังตั้งแต่ต้นทาง: bbox สูงเกิน
    # จริง ตัวละครเลยถูกย่อจนไม่เท่ากับมุมอื่น แล้วเท้าบานเป็นแผ่นแพนเค้ก
    segment_order: tuple[str, ...] = ("alpha", "rembg", "grabcut", "flatbg")
    # เติมรูในm ask ได้ไม่เกินกี่ส่วนของพื้นที่ตัวละคร
    #
    # ห้ามเติมทุกรู: หางที่ขดเป็นวงในมุมข้างล้อมพื้นหลังเอาไว้ ถ้าเติมหมด
    # ช่องว่างกลางวงหางจะกลายเป็นเนื้อ แล้วความ "หนา" ของช่วงสะโพกจะพุ่งไป
    # เท่าความยาวหางทั้งเส้น ต้นขาเลยออกมาหนาเป็นถัง
    fill_hole_frac: float = 0.02

    # --- visual hull ---
    voxel_res: int = 448            # จำนวน voxel ตามความสูงของตัวละคร
                                    # หัวสูงราว 1/7 ของตัว ที่ 256 เหลือแค่ ~36 voxel
                                    # ซึ่งน้อยเกินกว่าจะเก็บรูปปากกับกะโหลกไว้ได้
    # เบลอ occupancy ก่อน marching cubes
    # นอกจากลบเหลี่ยมแล้ว ยังทำหน้าที่ *หลอมก้อนที่ปั้นแยกกันให้กลืนเป็นเนื้อ
    # เดียวกัน* (ลำตัว + ก้อนปาก + หาง) ซึ่ง union แบบ boolean ทำไม่ได้
    # ต่ำกว่า ~2 จะเห็นรอยต่อเป็นจานแยกชิ้นระหว่างหัวกับไหล่
    hull_blur: float = 2.6
    iso_level: float = 0.5

    # วิธีสร้างหน้าตัดแนวนอน
    #   "hull"    = ตัดกันตรง ๆ ตามนิยาม visual hull -> หน้าตัดเป็นสี่เหลี่ยม
    #   "ellipse" = หน้าตัดเป็นวงรี/superellipse -> เหมือนร่างกายจริงมากกว่ามาก
    # ด้วยภาพแค่ 3 มุม (0/90/180) มีแค่สองแกนที่ให้ข้อมูลจริง หน้าตัดแบบ hull
    # จึงออกมาเป็นกล่องเสมอ "ellipse" แลกความเป๊ะของ silhouette ด้านข้าง
    # กับรูปทรงที่เป็นอินทรีย์กว่า ซึ่งคุ้มกว่ามากสำหรับตัวละคร
    carve_mode: str = "ellipse"
    cross_section_power: float = 2.2   # 2 = วงรี, สูงขึ้น = เข้าใกล้สี่เหลี่ยมมุมมน
    depth_falloff: float = 0.5         # ชิ้นส่วนที่แคบ (แขน) ได้ความลึกตามสัดส่วนยกกำลังนี้
    # เพดานอัตราส่วน ลึก/กว้าง ของ *หัว* (เหนือแนวคางขึ้นไป)
    #
    # ปิดไว้ (0) โดยค่าเริ่มต้น หัวสัตว์ปากยาวลึกกว่ากว้างสองเท่าเป็นเรื่องปกติ
    # การหั่นแล้วเอาส่วนที่หั่นมาแปะคืนเป็นก้อน "ปาก" ทำให้เกิดจานแบนคาดกลาง
    # หัวกับก้อนเห็ดบนกะโหลก ซึ่งแย่กว่าการปล่อยหัวไว้ตามที่มุมข้างบอกมาก
    #
    # เปิดเมื่อตัวละครคอเล็กกว่าหัวมากจนปากไปลากความลึกของบ่าทั้งแถว แล้ว
    # เกิดแผ่นแบนคาดรอบคอเหมือนปีกหมวก (ใช้คู่กับ snout_width)
    max_aspect: float = 0.0
    # --- คอ (ดู visual_hull._carve_neck) ---
    # ตัวละครไหล่ใหญ่ที่ไหล่ชนกรามไม่มีคอให้เห็นในมุมไหนเลย hull จึงเติมเนื้อ
    # เต็มช่องระหว่างคอกับยอดบ่า ได้หัวกลืนเป็นทรงกรวยเหมือนใส่ฮู้ด
    # ขั้นนี้เซาะซอกคอคืนมา โดยลดความลึกเฉพาะช่วงข้าง ๆ คอ ซึ่งไม่แตะ
    # เส้นขอบของมุมไหนเลย (ตัดอย่างเดียว ไม่เพิ่มเนื้อ)
    neck_carve: bool = True
    # ความกว้างลำคอ เป็นกี่เท่าของครึ่งความกว้างหัว
    neck_width: float = 1.25
    # ความยาวช่วงคอ เป็นกี่ส่วนของความสูงหัว
    neck_len: float = 0.42
    # สันบ่าใต้คางบางแค่ไหน เป็นกี่ส่วนของความลึกแถวนั้น (1 = ไม่เซาะ)
    neck_shoulder_min: float = 0.52

    # --- แนวคาง: จุดที่หัวจบและลำตัวเริ่ม (อ่านจากมุมข้าง) ---
    # มองหาในช่วงบนสุดกี่ส่วนของความสูง
    chin_search: float = 0.40
    # ขอบหน้าต้องถอยกลับอย่างน้อยกี่ส่วนของช่วงความลึกทั้งตัว จึงนับเป็นคาง
    chin_min_drop: float = 0.18
    # เพดาน ลึก/กว้าง ของ *ลำตัวกับขา* (ทุกแถวที่ไม่ใช่หัวและไม่ใช่เท้า)
    #
    # กฎกายภาพง่าย ๆ: ชิ้นส่วนของร่างกายไม่เคยลึกกว่าตัวเองกว้างมากนัก
    # ยกเว้นหัว (มีปากยื่น) กับเท้า (มีนิ้วยื่นไปข้างหน้า)
    #
    # ข้อนี้จำเป็นเพราะหางที่สะบัดอยู่ *ด้านหลังขา* ในภาพมุมข้าง จะเชื่อมติด
    # กับลำตัวเป็นก้อนเดียวใน silhouette การไล่ตามก้อนจึงแยกมันออกไม่ได้
    # ผลคือช่วงสะโพก/ต้นขาได้ความลึกเท่าความยาวหาง กลายเป็นแผ่นชั้นยื่นออก
    # ไปด้านหลัง เนื้อหางตัวจริงถูกปั้นใหม่จากภาพด้านหลังอยู่แล้ว จึงตัดทิ้ง
    # ตรงนี้ได้โดยไม่เสียอะไร
    body_aspect: float = 1.30
    # ช่วงบนสุดกี่ส่วนของความสูงที่นับเป็น "หัว" — ใช้เมื่อหาแนวคางไม่เจอ
    head_band: float = 0.16
    # ช่วงล่างสุดกี่ส่วนของความสูงที่นับเป็น "เท้า" (ได้รับยกเว้นเช่นกัน)
    foot_band: float = 0.085
    # ความกว้างของก้อนปากที่คืนกลับมา เป็นกี่เท่าของความกว้างหัว
    # 0 = ไม่คืน (ตัวละครจะหน้าสั้นกุดแต่คอเนียน)
    snout_width: float = 1.15
    # ความกว้างของสันหนามที่คืนกลับมา เป็นกี่เท่าของความกว้างหัว
    # หนามอยู่บนแนวกลางหลัง จึงต้องแคบกว่าลำตัวมาก 0 = ไม่คืนหนาม
    crest_width: float = 0.45
    crest_min: float = 2.0          # ส่วนยื่นต้องลึกกว่านี้ (voxel) จึงนับเป็นหนาม
    # เบลอเขตสันหนามเบากว่าลำตัว เพื่อให้หนามไม่ถูกละลายทิ้ง
    # (ใช้ค่า detail_blur ตัวเดียวกับมือ/เท้า)
    crest_sharp: bool = True
    # ใช้เฉพาะก้อนที่ใหญ่ที่สุดของ mask ด้านข้างในแต่ละแถว
    # ตัดส่วนที่ยื่นออกไปอย่างหางหรือเป้สะพายหลังทิ้ง ไม่ให้ไปพองความหนาทั้งตัว
    side_main_component_only: bool = True
    # เกลาโปรไฟล์ความลึก/ความกว้างตามแนวตั้งกี่แถว ก่อนเอาไปปั้นหน้าตัด
    # 0 = ไม่เกลา ซึ่งจะได้ผิวเป็นวงแหวนขั้นบันได
    profile_smooth: float = 3.0
    # เกลาโปรไฟล์ความลึก *เฉพาะช่วงขา* เพิ่มอีกชั้น — ดูเหตุผลใน
    # visual_hull._fill_elliptical (เกลาแรงทั้งตัวจะทำให้ปากหายไป)
    leg_profile_smooth: float = 28.0
    # ทิ้งก้อนที่ไม่ต่อกับตัว เมื่อเล็กกว่าสัดส่วนนี้ของก้อนหลัก (0 = ไม่ทิ้ง)
    drop_loose: float = 0.03
    leg_band_top: float = 0.45      # ขอบบนของเขตขา เป็นสัดส่วนของความสูง
    leg_band_blend: float = 0.08    # ไล่ระดับที่ขอบบนกี่ส่วนของความสูง
    # เติมรอยเว้าหลังขา: หน้าต่าง min filter เป็นสัดส่วนของความสูง (0 = ไม่เติม)
    leg_fill_dip: float = 0.22      # หน้าต่างต้องกว้างกว่าแอ่งที่จะเติม
    leg_fill_floor: float = 0.08    # ไม่เติมใต้ระดับนี้ (เขตเท้า)
    leg_fill_blend: float = 0.10    # ไล่ระดับขอบล่างกี่ส่วนของความสูง
    # ลบส่วนยื่นที่บางกว่านี้ (หน่วย voxel) ออกจาก silhouette ทั้งสองแกน
    # หนามสันหลัง เขา ครีบ ผมแหลม ถ้าไม่ลบจะกลายเป็นสันวงแหวนรอบตัว
    # และทำให้รูปทรงกระโดดเป็นขั้นบันไดตามแนวตั้ง ตั้ง 0 เพื่อเก็บไว้ทั้งหมด
    spike_open: int = 3
    # เกลาขอบ silhouette ตามแนวตั้งกี่ voxel ก่อนปั้นหน้าตัด
    # เส้นขอบที่สั่น 1-2 px ระหว่างแถว จะกลายเป็นลอนถี่พาดทั่วตัวถ้าไม่เกลา
    silhouette_smooth: float = 1.5
    # median filter บนโปรไฟล์ขอบหน้า/ขอบหลัง (หน่วย voxel ตามแนวตั้ง)
    # ตัดหนามสันหลังที่เป็นค่ากระโดดออกไป โดยไม่ทำให้รูปทรงจริงเบลอ
    # ต้องกว้างกว่าระยะห่างระหว่างหนามสองอัน จึงจะตัดได้หมด
    depth_median: int = 13

    # --- หาง / ส่วนยื่นด้านหลัง ---
    # เก็บก้อนที่อยู่ด้านหลังลำตัวใน mask ด้านข้าง กลับมาเป็นปริมาตรของตัวเอง
    # แทนที่จะทิ้งไป ทำให้ได้เนื้อหางที่กระดูกหางยึดเกาะได้จริง
    keep_tail: bool = True
    # --- ลากหางจากภาพด้านหลัง (ภาพเดียวเป็นแหล่งอ้างอิง) ---
    # หางห้อยทับกางเกงอยู่ใน silhouette จึงต้องแยกด้วยสี ไม่ใช่ขอบ
    # เริ่มมองหาหางที่กี่ส่วนจากยอดหัวลงมา
    # ต้องเริ่ม *ใต้เข็มขัด* เพราะเข็มขัดเป็นแถบกว้างพาดทั้งตัวและสีไม่ใช่
    # เสื้อผ้า ตัวติดตามจะออกตัวบนเข็มขัดแล้วไหลไปตามขอบกางเกงแทนที่จะตามหาง
    tail_band_top: float = 0.50
    tail_max_jump: float = 0.06     # ศูนย์กลางหางขยับได้กี่ส่วนของ canvas ต่อแถว
